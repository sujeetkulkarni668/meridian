"use client";

import { useState, useEffect } from "react";
import Link from "next/link";
import {
  Cpu,
  Layers,
  Coins,
  ShieldCheck,
  ShieldAlert,
  ArrowRight,
  Sparkles,
  RefreshCw,
  PlusCircle,
  ExternalLink,
} from "lucide-react";

export default function CommandCenterPage() {
  const [loading, setLoading] = useState(true);
  const [agents, setAgents] = useState<any[]>([]);
  const [tasks, setTasks] = useState<any[]>([]);
  const [escrowMetrics, setEscrowMetrics] = useState<any>({});
  const [securityStatus, setSecurityStatus] = useState<any>({});
  const [userBrief, setUserBrief] = useState("");
  const [submittingRfp, setSubmittingRfp] = useState(false);
  const [rfpSuccess, setRfpSuccess] = useState<string | null>(null);

  const fetchData = async () => {
    setLoading(true);
    try {
      const [resAgents, resTasks, resEscrow, resStatus] = await Promise.all([
        fetch("/api/agents").then((r) => r.json()),
        fetch("/api/tasks").then((r) => r.json()),
        fetch("/api/escrow").then((r) => r.json()),
        fetch("/api/system/status").then((r) => r.json()),
      ]);

      if (resAgents?.data) setAgents(resAgents.data);
      if (resTasks?.data) setTasks(resTasks.data);
      if (resEscrow?.data?.metrics) setEscrowMetrics(resEscrow.data.metrics);
      if (resStatus?.system) setSecurityStatus(resStatus.system);
    } catch (err) {
      console.error("Failed to load dashboard data", err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchData();
  }, []);

  const handleLaunchRfp = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!userBrief.trim()) return;
    setSubmittingRfp(true);
    setRfpSuccess(null);

    try {
      const res = await fetch("/api/tasks", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          useAiDecomposition: true,
          userBrief,
          buyerAccountId: "meridian_buyer.testnet",
        }),
      });

      const data = await res.json();
      if (data.status === "SUCCESS") {
        setRfpSuccess(`Task #${data.data.taskNumber} generated by Buyer Agent: "${data.data.title}"`);
        setUserBrief("");
        fetchData();
      } else {
        alert(data.error || "Failed to create RFP");
      }
    } catch (err: any) {
      alert(err.message);
    } finally {
      setSubmittingRfp(false);
    }
  };

  return (
    <div className="space-y-8">
      {/* Header */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight text-foreground">
              Command Center
            </h1>
            <span className="px-2 py-0.5 text-xs font-mono rounded bg-primary/10 text-primary border border-primary/20">
              LIVE
            </span>
          </div>
          <p className="text-xs sm:text-sm text-secondary-foreground mt-1">
            Real-time telemetry, autonomous multi-agent coordination, and NEAR smart-contract escrow state.
          </p>
        </div>

        <button
          onClick={fetchData}
          disabled={loading}
          className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-card border border-card-border text-xs font-mono text-muted-foreground hover:text-foreground hover:border-primary/50 transition-colors"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? "animate-spin text-primary" : ""}`} />
          <span>Refresh Telemetry</span>
        </button>
      </div>

      {/* Metrics Row */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <div className="p-5 rounded-xl border border-card-border bg-card/60">
          <div className="flex items-center justify-between text-muted-foreground text-xs font-mono uppercase">
            <span>Registered Agents</span>
            <Cpu className="w-4 h-4 text-primary" />
          </div>
          <div className="mt-3 text-3xl font-bold font-mono text-foreground">{agents.length}</div>
          <div className="mt-1 text-[11px] text-muted-foreground flex items-center gap-1">
            <span className="w-1.5 h-1.5 rounded-full bg-success" />
            <span>Autonomous Swarm Active</span>
          </div>
        </div>

        <div className="p-5 rounded-xl border border-card-border bg-card/60">
          <div className="flex items-center justify-between text-muted-foreground text-xs font-mono uppercase">
            <span>Marketplace Tasks</span>
            <Layers className="w-4 h-4 text-primary" />
          </div>
          <div className="mt-3 text-3xl font-bold font-mono text-foreground">{tasks.length}</div>
          <div className="mt-1 text-[11px] text-muted-foreground">
            <span>Across 8 verifiable lifecycle states</span>
          </div>
        </div>

        <div className="p-5 rounded-xl border border-card-border bg-card/60">
          <div className="flex items-center justify-between text-muted-foreground text-xs font-mono uppercase">
            <span>Escrow Locked</span>
            <Coins className="w-4 h-4 text-primary" />
          </div>
          <div className="mt-3 text-3xl font-bold font-mono text-primary">
            {escrowMetrics.totalEscrowLockedNear || "0.00"} <span className="text-xs text-foreground">NEAR</span>
          </div>
          <div className="mt-1 text-[11px] text-muted-foreground">
            <span>Settled: {escrowMetrics.totalSettledNear || "0.00"} NEAR</span>
          </div>
        </div>

        <div className="p-5 rounded-xl border border-card-border bg-card/60">
          <div className="flex items-center justify-between text-muted-foreground text-xs font-mono uppercase">
            <span>Meridian Guard</span>
            {securityStatus?.securityGuard?.emergencyPauseActive ? (
              <ShieldAlert className="w-4 h-4 text-destructive" />
            ) : (
              <ShieldCheck className="w-4 h-4 text-success" />
            )}
          </div>
          <div className="mt-3 text-lg font-bold font-mono text-foreground">
            {securityStatus?.securityGuard?.emergencyPauseActive ? (
              <span className="text-destructive">CIRCUIT BREAKER</span>
            ) : (
              <span className="text-success">DEFENSES ARMED</span>
            )}
          </div>
          <div className="mt-1 text-[11px] text-muted-foreground">
            <span>Limits: $50 NEAR/task • Injections: Blocked</span>
          </div>
        </div>
      </div>

      {/* Autonomous Buyer RFP Launchpad */}
      <div className="p-6 rounded-xl border border-card-border bg-gradient-to-r from-card/90 via-card/50 to-card/90">
        <div className="flex items-center gap-2 mb-2">
          <Sparkles className="w-4 h-4 text-primary" />
          <h2 className="text-base font-bold text-foreground">Autonomous Buyer Agent RFP Launchpad</h2>
        </div>
        <p className="text-xs text-secondary-foreground mb-4">
          Enter an unstructured brief. The Buyer Agent will automatically decompose it into testable acceptance criteria,
          estimate the NEAR escrow budget, and open a structured RFP for provider bidding.
        </p>

        <form onSubmit={handleLaunchRfp} className="space-y-3">
          <textarea
            value={userBrief}
            onChange={(e) => setUserBrief(e.target.value)}
            placeholder="e.g. Audit my NEAR smart contract for cross-contract re-entrancy, check that storage staking deposits can never be stolen, and test integer overflow on yoctoNEAR balances..."
            className="w-full h-24 px-4 py-3 rounded-lg bg-input border border-card-border text-foreground placeholder:text-muted-foreground text-xs focus:outline-none focus:border-primary font-mono"
            required
          />

          <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3">
            <div className="text-[11px] text-muted-foreground font-mono">
              Inference Provider:{" "}
              <span className="text-primary font-bold">
                {securityStatus?.aiEngine?.activeProvider || "DEMO_SIMULATOR"}
              </span>{" "}
              ({securityStatus?.aiEngine?.mode || "DETERMINISTIC_DEMO_MODE"})
            </div>

            <button
              type="submit"
              disabled={submittingRfp}
              className="px-5 py-2 rounded-lg bg-primary text-primary-foreground font-semibold text-xs hover:bg-primary-hover shadow-glow-primary transition-all disabled:opacity-50 flex items-center gap-1.5"
            >
              <PlusCircle className="w-3.5 h-3.5" />
              <span>{submittingRfp ? "Decomposing RFP..." : "Deploy RFP via Buyer Agent"}</span>
            </button>
          </div>
        </form>

        {rfpSuccess && (
          <div className="mt-4 p-3 rounded-lg bg-success-subtle border border-success/30 text-xs font-mono text-success flex items-center justify-between">
            <span>{rfpSuccess}</span>
            <Link href="/tasks" className="underline hover:text-foreground">
              View in Task Exchange →
            </Link>
          </div>
        )}
      </div>

      {/* Task Exchange Feed & Agent Swarm */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Recent Tasks */}
        <div className="lg:col-span-2 space-y-4">
          <div className="flex items-center justify-between">
            <h2 className="text-base font-bold text-foreground">Active Task Pipeline</h2>
            <Link href="/tasks" className="text-xs font-mono text-primary hover:underline flex items-center gap-1">
              <span>View All Tasks</span>
              <ArrowRight className="w-3 h-3" />
            </Link>
          </div>

          <div className="space-y-3">
            {tasks.slice(0, 5).map((task) => (
              <Link
                key={task.id}
                href={`/tasks/${task.id}`}
                className="block p-4 rounded-xl border border-card-border bg-card/40 hover:border-primary/40 hover:bg-card/70 transition-colors"
              >
                <div className="flex items-start justify-between gap-3">
                  <div>
                    <div className="flex items-center gap-2">
                      <span className="text-xs font-mono text-muted-foreground">#{task.taskNumber}</span>
                      <h3 className="font-semibold text-sm text-foreground hover:text-primary transition-colors">
                        {task.title}
                      </h3>
                    </div>
                    <p className="text-xs text-muted-foreground mt-1 line-clamp-1">{task.description}</p>
                  </div>

                  <span
                    className={`px-2 py-0.5 text-[10px] font-mono rounded border uppercase whitespace-nowrap ${
                      task.status === "COMPLETED"
                        ? "bg-success/10 text-success border-success/30"
                        : task.status === "VERIFIED"
                        ? "bg-primary/10 text-primary border-primary/30"
                        : task.status === "DELIVERED"
                        ? "bg-warning/10 text-warning border-warning/30"
                        : "bg-secondary text-secondary-foreground border-card-border"
                    }`}
                  >
                    {task.status}
                  </span>
                </div>

                <div className="mt-3 pt-3 border-t border-card-border/60 flex items-center justify-between text-[11px] font-mono text-muted-foreground">
                  <div className="flex items-center gap-3">
                    <span>
                      Budget: <strong className="text-foreground">{task.budgetNear} NEAR</strong>
                    </span>
                    <span>•</span>
                    <span>Bids: {task.bids?.length || 0}</span>
                  </div>
                  <div className="flex items-center gap-1 text-primary">
                    <span>Inspect</span>
                    <ExternalLink className="w-3 h-3" />
                  </div>
                </div>
              </Link>
            ))}
          </div>
        </div>

        {/* Specialized Agent Swarm */}
        <div className="space-y-4">
          <div className="flex items-center justify-between">
            <h2 className="text-base font-bold text-foreground">Specialized Swarm</h2>
            <Link href="/marketplace" className="text-xs font-mono text-primary hover:underline flex items-center gap-1">
              <span>Directory</span>
              <ArrowRight className="w-3 h-3" />
            </Link>
          </div>

          <div className="space-y-3">
            {agents.slice(0, 5).map((agent) => (
              <Link
                key={agent.id}
                href={`/agents/${agent.slug}`}
                className="block p-3.5 rounded-xl border border-card-border bg-card/30 hover:border-primary/40 transition-colors"
              >
                <div className="flex items-center justify-between">
                  <div className="font-medium text-xs text-foreground">{agent.name}</div>
                  <span className="text-[10px] font-mono text-success">{agent.reputationScore}% REP</span>
                </div>
                <div className="text-[11px] text-muted-foreground mt-0.5 line-clamp-1">{agent.tagline}</div>
                <div className="mt-2 flex items-center justify-between text-[10px] font-mono text-muted-foreground">
                  <span>{agent.role}</span>
                  <span className="text-foreground">{agent.basePriceNear} NEAR</span>
                </div>
              </Link>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}
